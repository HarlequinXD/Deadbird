/* Bakes the foot IK into tables (game/gait_bake.h) for builds without live foot IK (the PS1).
   Runs the real locomotion with the live IK on flat ground at a range of steady speeds, from
   standing to sprinting, and records the six leg bone rotations and the hip offset at
   GAIT_PHASES points through the stride. Played back by the stride phase the movement already
   advances with the distance covered, the planted feet stay put - no sliding.
   Troopers share Deadbird's leg skeleton, so one table serves both.
   usage: bakegait game/gait_bake.h */
#include <stdio.h>
#include <string.h>
#include "gte.h"
#include "model.h"
#include "player.h"
#include "level.h"
#include "assets.h"
#undef DEMON_MESH_NO_DATA
#include "demon_mesh.h"

#define PHASES 64
#define NV 56                      /* 6 bones x 9 rotation entries + hip x, y */
#define MAXS 256

static Player pl;
static const int LEG[6] = { DEMON_BONE_THIGH_L, DEMON_BONE_CALF_L, DEMON_BONE_HOOF_L,
                            DEMON_BONE_THIGH_R, DEMON_BONE_CALF_R, DEMON_BONE_HOOF_R };

static void grab(const Player *p, s32 *v)
{
    int b, i, j;
    for (b = 0; b < 6; b++)
        for (i = 0; i < 3; i++)
            for (j = 0; j < 3; j++) v[b * 9 + i * 3 + j] = p->bone_pose[LEG[b]].m[i][j];
    v[54] = p->pelvis_x; v[55] = p->pelvis_y;
}

int main(int argc, char **argv)
{
    /* stick magnitudes: standing, walking, jogging, running; the last held long enough to sprint */
    static const int MAG[] = { 0, 900, 1500, 2100, 4096, 4096 };
    static const int HOLD[] = { 120, 200, 200, 200, 200, 200 };
    static const u32 PAD[] = { 0, 0, 0, 0, 0, BTN_SPRINT };   /* the last: sprinting */
    const int NS = (int)(sizeof(MAG) / sizeof(MAG[0]));
    static s32 out[16][PHASES][NV];
    static int key[16];
    FILE *f = fopen(argc > 1 ? argv[1] : "gait_bake.h", "w");
    Model m;
    int s, i, k, ns = 0, walk_top = 0;
    if (!f) return 1;
    level_init();
    level_debug_flat(1);           /* flat ground at 0, no walls */
    assets_init();
    m = asset_demon;
    m.bones = (const DBONE *)demon_bones; m.nbones = DEMON_NBONES;
    player_init(&m);
    for (s = 0; s < NS; s++) {
        static int ph[MAXS];
        static s32 val[MAXS][NV];
        int n = 0, b;
        s32 spd = 0;
        player_reset(&pl, 0, 0, 0);
        for (i = 0; i < HOLD[s]; i++) { player_update(&pl, PAD[s], 0, MAG[s]); player_pose(&pl, &m); }
        /* record two strides (or a while, standing) */
        for (i = 0; i < MAXS; i++) {
            player_update(&pl, PAD[s], 0, MAG[s]); player_pose(&pl, &m);
            ph[n] = pl.phase & 65535; grab(&pl, val[n]); spd += pl.speed16; n++;
        }
        spd /= n;
        for (b = 0; b < PHASES; b++) {
            int c = b * (65536 / PHASES), best = -1;
            if (MAG[s] == 0) { memcpy(out[ns][b], val[n - 1], sizeof(out[ns][b])); continue; }   /* standing: one pose */
            /* the consecutive pair of samples whose phases straddle c (phase wraps at 65536) */
            for (i = 0; i + 1 < n && best < 0; i++) {
                int a0 = ph[i], a1 = ph[i + 1];
                if (a1 < a0) a1 += 65536;
                if ((c >= a0 && c <= a1) || (c + 65536 >= a0 && c + 65536 <= a1)) best = i;
            }
            if (best < 0) { fprintf(stderr, "speed %d: phase %d not covered\n", MAG[s], c); return 1; }
            {
                int a0 = ph[best], a1 = ph[best + 1], cc = c;
                s32 t;
                if (a1 < a0) a1 += 65536;
                if (cc < a0) cc += 65536;
                t = a1 > a0 ? (s32)((long long)(cc - a0) * 4096 / (a1 - a0)) : 0;
                for (k = 0; k < NV; k++) out[ns][b][k] = val[best][k] + (s32)(((long long)(val[best + 1][k] - val[best][k]) * t) >> 12);
            }
        }
        if (ns && spd <= key[ns - 1]) spd = key[ns - 1] + 1;    /* keys strictly rising */
        if (pl.runw < 2048) walk_top = ns;
        key[ns++] = spd;
        fprintf(stderr, "stick %4d: speed16 %d, run %d, amp %d\n", MAG[s], spd, pl.runw, pl.amp);
    }
    fprintf(f, "/* generated by platform/headless/bakegait.c (make bakegait && ./bakegait ../../game/gait_bake.h):\n"
               "   the foot IK baked on flat ground - per speed, per stride phase: the 6 leg bone rotations\n"
               "   (thigh, calf, hoof L then R; 3x3, 4096 = 1) and the hip offset x, y */\n");
    fprintf(f, "#define GAIT_SPEEDS %d\n#define GAIT_PHASES %d\n#define GAIT_SHIFT %d\n", ns, PHASES, PHASES == 64 ? 10 : 11);
    fprintf(f, "#define GAIT_WALK_TOP %d                /* the fastest walk; the next table is the run */\n", walk_top);
    fprintf(f, "static const s32 gait_key[GAIT_SPEEDS] = {");
    for (s = 0; s < ns; s++) fprintf(f, "%s%d", s ? ", " : " ", key[s]);
    fprintf(f, " };\nstatic const s16 gait_tab[GAIT_SPEEDS][GAIT_PHASES][%d] = {\n", NV);
    for (s = 0; s < ns; s++) {
        fprintf(f, "  {\n");
        for (i = 0; i < PHASES; i++) {
            fprintf(f, "    {");
            for (k = 0; k < NV; k++) fprintf(f, "%s%d", k ? "," : "", out[s][i][k]);
            fprintf(f, "},\n");
        }
        fprintf(f, "  },\n");
    }
    fprintf(f, "};\n");
    fclose(f);
    return 0;
}
