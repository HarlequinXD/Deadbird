#!/usr/bin/env python3
"""Write engine/fw/ACTIONS.md: the FSM action library, from the table in engine/fw/actions.c."""
import re, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, 'engine/fw/actions.c')).read()
rows = re.findall(r'\{ "(\w+)", \w+, \d, \{[^}]*\}, "([^"]*)", "([^"]*)", "(\w+)" \}', src)
out = ['# FSM actions', '', 'Generated by `tools/list_actions.py` from `engine/fw/actions.c`. Each is a framework API call',
       '(`engine/fw/fw.h`). Use `do` for once-on-entering (in order; Wait / MoveTo hold the list) and `every`',
       'for every tick. Sense actions raise their event; the state\'s `on EVENT state` lines pick it up.', '']
group = None
for name, args, help_, g in rows:
    if g != group:
        out += ['', '## ' + g, '', '| action | arguments | what it does |', '|---|---|---|']
        group = g
    out.append('| `%s` | %s | %s |' % (name, ' '.join('*%s*' % a for a in args.split()) or '-', help_))
open(os.path.join(root, 'engine/fw/ACTIONS.md'), 'w').write('\n'.join(out) + '\n')
print(len(rows), 'actions')
