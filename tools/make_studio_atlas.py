#!/usr/bin/env python3
"""Bake the Studio's pixel-art atlas into studio/studio_atlas.h (RGBA, run-length coded):
Deadbird's fire font (and a white copy for tinting) with a few extra glyphs, and the UI kit
(assets/src/kit_tex.png: forged iron, bone and molten panels and buttons)."""
import os
import numpy as np
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'src')
W, H = 512, 128
FONT = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!.:-'/+?<> "
EXTRA = {   # 6 x 8 shapes for glyphs the game's font lacks
    '=': ["......", "......", "######", "......", "######", "......", "......", "......"],
    '(': ["...##.", "..##..", ".##...", ".##...", ".##...", "..##..", "...##.", "......"],
    ')': [".##...", "..##..", "...##.", "...##.", "...##.", "..##..", ".##...", "......"],
    ',': ["......", "......", "......", "......", "..##..", "..##..", ".##...", "......"],
    '_': ["......", "......", "......", "......", "......", "......", "######", "......"],
    '"': [".#..#.", ".#..#.", "......", "......", "......", "......", "......", "......"],
    '%': ["##...#", "##..#.", "...#..", "..#...", ".#....", "#...##", "....##", "......"],
    '*': ["......", "#.#.#.", ".###..", "#####.", ".###..", "#.#.#.", "......", "......"],
    '#': [".#.#..", "#####.", ".#.#..", ".#.#..", "#####.", ".#.#..", "......", "......"],
}
font = np.array(Image.open(os.path.join(SRC, 'font.png')))
pal = Image.open(os.path.join(SRC, 'font.png')).getpalette()
# extra glyphs in palette indices: fill by row with the fire ramp, outline 1 around
extra_idx = np.zeros((10, 8 * len(EXTRA)), np.uint8)
for g, (ch, rows) in enumerate(EXTRA.items()):
    m = np.zeros((10, 8), bool)
    for r, row in enumerate(rows):
        for c, x in enumerate(row):
            if x == '#': m[r + 1, c + 1] = True
    cell = np.zeros((10, 8), np.uint8)
    for r in range(10):
        for c in range(8):
            if m[r, c]: cell[r, c] = min(8, 2 + max(0, r - 1))
    for r in range(10):
        for c in range(8):
            if not m[r, c] and any(0 <= r + dr < 10 and 0 <= c + dc < 8 and m[r + dr, c + dc] for dr in (-1, 0, 1) for dc in (-1, 0, 1)):
                cell[r, c] = 1
    extra_idx[:, g * 8:(g + 1) * 8] = cell
def rgba(idx, white):
    out = np.zeros(idx.shape + (4,), np.uint8)
    for i in range(1, 9):
        m = idx == i
        if white:
            if i == 1: col = (20, 14, 12)
            else: v = 255 - (i - 2) * 14; col = (v, v, v)
        else: col = tuple(pal[i * 3:i * 3 + 3])
        out[m] = col + (255,)
    return out
atlas = np.zeros((H, W, 4), np.uint8)
atlas[0:2, 0:2] = 255                                   # white texel
atlas[0:32, 8:136] = rgba(font, False)
atlas[0:32, 136:264] = rgba(font, True)
atlas[32:42, 8:8 + extra_idx.shape[1]] = rgba(extra_idx, False)
atlas[32:42, 136:136 + extra_idx.shape[1]] = rgba(extra_idx, True)
kit = np.array(Image.open(os.path.join(SRC, 'kit_tex.png')).convert('RGBA'))
atlas[64:128, 0:256] = kit[0:64, 0:256]
Image.fromarray(atlas, 'RGBA').save('/tmp/studio_atlas.png')
raw = atlas.reshape(-1, 4)
# run-length: (count, r, g, b, a) runs of equal pixels, count 1..255
out = bytearray(); i = 0; n = len(raw)
while i < n:
    j = i
    while j < n and j - i < 255 and (raw[j] == raw[i]).all(): j += 1
    out += bytes((j - i,)) + bytes(raw[i]); i = j
chars = FONT + ''.join(EXTRA.keys())
with open(os.path.join(ROOT, 'studio', 'studio_atlas.h'), 'w') as o:
    o.write('/* generated by tools/make_studio_atlas.py: Deadbird\'s fire font (+ a white copy) and UI kit */\n')
    o.write('#define SA_W %d\n#define SA_H %d\n' % (W, H))
    o.write('/* glyphs: 8x10 cells, 16 a row from (8,0) fire / (136,0) white; then the extras from row 32 */\n')
    o.write('static const char sa_chars[] = "%s";\n' % chars.replace('\\', '\\\\').replace('"', '\\"'))
    o.write('#define SA_FONT_BASE %d\n' % len(FONT))
    o.write('static const unsigned char sa_rle[%d] = {\n' % len(out))
    for k in range(0, len(out), 48): o.write(','.join(str(b) for b in out[k:k + 48]) + ',\n')
    o.write('};\n')
print('atlas rle', len(out))
