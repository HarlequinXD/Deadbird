#!/usr/bin/env python3
"""Title logo -> PS1 8bpp CLUT TIM.
Keys out the light checkerboard background, crops, scales to 320 px wide, quantises to
255 colours with PS1-style 4x4 ordered dither (index 0 = transparent), and stores the two
160 px halves in one TIM at VRAM (832,256): left half at rows 0..H-1, right half at 128..
CLUT at (0,484)."""
import os, struct
from PIL import Image
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = Image.open(os.path.join(ROOT, 'assets', 'src', 'deadbird_logo.png')).convert('RGB')
a = np.asarray(src).astype(int)
mn, mx = a.min(2), a.max(2)
bg = (mn > 170) & (mx - mn < 30)                       # white / grey checker background
alpha = (~bg).astype(np.uint8) * 255
rgba = np.dstack([a.astype(np.uint8), alpha])
im = Image.fromarray(rgba, 'RGBA')
im = im.crop(im.split()[3].getbbox())
W = 320
H = round(im.height * W / im.width)
im = im.resize((W, H), Image.LANCZOS)
px = np.asarray(im).astype(int)
opaque = px[..., 3] > 140

# palette from opaque pixels, then ordered-dither mapping onto it
op = Image.fromarray(px[..., :3][opaque][None].astype(np.uint8))
pal = np.array(op.quantize(255, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).getpalette()[:255 * 3]).reshape(-1, 3)
pal = np.clip(np.round(pal / 8), 0, 31)
pal8 = pal * 8 + pal // 4
DM = np.array([[-4, 0, -3, 1], [2, -2, 3, -1], [-3, 1, -4, 0], [3, -1, 2, -2]], float) * 2.0
yy, xx = np.mgrid[0:H, 0:W]
tgt = px[..., :3] + DM[yy % 4, xx % 4][..., None]
d2 = ((tgt[..., None, :] - pal8[None, None]) ** 2).sum(-1)
idx = (d2.argmin(-1) + 1).astype(np.uint8)
idx[~opaque] = 0

clut = [0] + [int(r) | (int(g) << 5) | (int(b) << 10) for r, g, b in pal]
clut = [c if (c or i == 0) else 0x8000 for i, c in enumerate(clut)]
clut += [0] * (256 - len(clut))

TW, TH = W // 2, 128 + H                                # two halves stacked
tex = np.zeros((TH, TW), np.uint8)
tex[:H] = idx[:, :TW]
tex[128:128 + H] = idx[:, TW:]
tim = struct.pack('<II', 0x10, 0x09)
tim += struct.pack('<IHHHH', 12 + 512, 0, 484, 256, 1) + struct.pack('<256H', *clut)
tim += struct.pack('<IHHHH', 12 + TW * TH, 832, 256, TW // 2, TH) + tex.tobytes()

open(os.path.join(ROOT, 'assets', 'logo.tim'), 'wb').write(tim)
with open(os.path.join(ROOT, 'assets', 'logo_tim.h'), 'w') as f:
    f.write(f'/* title logo, 8bpp TIM ({len(tim)} bytes). Generated by tools/make_logo.py */\n')
    f.write(f'#define LOGO_TIM_SIZE {len(tim)}\n#define LOGO_W {W}\n#define LOGO_H {H}\n')
    f.write(f'static const unsigned char logo_tim[{len(tim)}] = {{\n')
    for i in range(0, len(tim), 24):
        f.write('  ' + ','.join(str(b) for b in tim[i:i + 24]) + ',\n')
    f.write('};\n')
# preview of exactly what the PS1 sees
rgb = (np.array([[c & 31, (c >> 5) & 31, (c >> 10) & 31] for c in clut]) * 8)[idx]
rgb[idx == 0] = (30, 0, 0)
Image.fromarray(rgb.astype(np.uint8)).resize((W * 3, H * 3), Image.NEAREST).save('/tmp/db/logo_preview.png')
print('logo', W, 'x', H, 'tim', len(tim), 'bytes')
