#!/usr/bin/env python3
"""Bakes the Studio's full-resolution UI fonts: each glyph's outline (printable ASCII), curves
flattened to line segments, into engine/studio/ui_fonts.h. The engine rasterises them at whatever
pixel size the screen needs (engine/studio/sui.c), so text stays sharp at any resolution.

  python3 tools/fonts/make_ui_fonts.py

Fonts: Inter (Regular, SemiBold, Bold, Display Black) and DejaVu Sans Mono; both licences allow
embedding (tools/fonts/LICENSES.txt).
"""
import math, os, sys
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen

FONTS = [   # sui.h order: FONT_REGULAR, FONT_SEMIBOLD, FONT_BOLD, FONT_MONO, FONT_FIRE
    "/usr/share/fonts/opentype/inter/Inter-Regular.otf",
    "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf",
    "/usr/share/fonts/opentype/inter/Inter-Bold.otf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
    "/usr/share/fonts/opentype/inter/InterDisplay-Black.otf",
]
FIRST, LAST = 32, 126

class Flatten(BasePen):
    def __init__(self, gs, tol):
        super().__init__(gs)
        self.tol = tol; self.contours = []; self.cur = None
    def _moveTo(self, p): self.cur = [p]
    def _lineTo(self, p): self.cur.append(p)
    def _n(self, pts):
        l = sum(math.dist(pts[i], pts[i + 1]) for i in range(len(pts) - 1))
        return max(2, min(16, int(math.ceil(math.sqrt(l / self.tol)))))
    def _qCurveToOne(self, p1, p2):
        p0 = self.cur[-1]; n = self._n([p0, p1, p2])
        for i in range(1, n + 1):
            t = i / n; a = (1 - t) ** 2; b = 2 * (1 - t) * t; c = t * t
            self.cur.append((a * p0[0] + b * p1[0] + c * p2[0], a * p0[1] + b * p1[1] + c * p2[1]))
    def _curveToOne(self, p1, p2, p3):
        p0 = self.cur[-1]; n = self._n([p0, p1, p2, p3])
        for i in range(1, n + 1):
            t = i / n; a = (1 - t) ** 3; b = 3 * (1 - t) ** 2 * t; c = 3 * (1 - t) * t * t; d = t ** 3
            self.cur.append((a * p0[0] + b * p1[0] + c * p2[0] + d * p3[0], a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1]))
    def _closePath(self):
        if self.cur and len(self.cur) > 2:
            if self.cur[0] == self.cur[-1]: self.cur.pop()
            self.contours.append(self.cur)
        self.cur = None
    _endPath = _closePath

out = []
out.append("/* The Studio's full-resolution UI fonts: glyph outlines as line loops (font units, y up).")
out.append("   Generated by tools/fonts/make_ui_fonts.py - don't edit. Inter (OFL 1.1), DejaVu Sans Mono")
out.append("   (Bitstream Vera licence): tools/fonts/LICENSES.txt. */")
out.append("#ifndef UI_FONTS_H\n#define UI_FONTS_H\n")
out.append("typedef struct { short adv, first, ncont; } UiGlyph;   /* first: index into the font's contour list */")
out.append("typedef struct { short upm, asc, cap; const UiGlyph *g; const unsigned short *cont; const short *pts; } UiFont;")
out.append("#define UI_FONT_FIRST %d\n#define UI_FONT_LAST %d\n" % (FIRST, LAST))
names = []
total = 0
for fi, path in enumerate(FONTS):
    f = TTFont(path)
    gs = f.getGlyphSet(); cmap = f.getBestCmap(); upm = f["head"].unitsPerEm
    asc = f["hhea"].ascent
    cap = getattr(f["OS/2"], "sCapHeight", 0) or int(upm * 0.73)
    glyphs = []; conts = []; pts = []
    for ch in range(FIRST, LAST + 1):
        gn = cmap.get(ch)
        if gn is None: glyphs.append((upm // 2, len(conts), 0)); continue
        pen = Flatten(gs, upm / 160.0)
        gs[gn].draw(pen)
        adv = f["hmtx"][gn][0]
        first = len(conts)
        for c in pen.contours:
            conts.append(len(pts) // 2 + len(c))        # end (exclusive) in points
            for (x, y) in c: pts += [int(round(x)), int(round(y))]
        glyphs.append((adv, first, len(pen.contours)))
    n = "uf%d" % fi; names.append(n)
    out.append("static const UiGlyph %s_g[%d] = {" % (n, len(glyphs)))
    out.append(",".join("{%d,%d,%d}" % g for g in glyphs) + "};")
    out.append("static const unsigned short %s_c[%d] = {" % (n, max(1, len(conts))))
    out.append(",".join(str(c) for c in conts) or "0"); out.append("};")
    out.append("static const short %s_p[%d] = {" % (n, max(1, len(pts))))
    for i in range(0, len(pts), 40): out.append(",".join(str(p) for p in pts[i:i + 40]) + ",")
    out.append("};")
    total += len(pts) // 2
    out.append("")
out.append("static const UiFont ui_fonts[%d] = {" % len(FONTS))
for fi, path in enumerate(FONTS):
    f = TTFont(path); upm = f["head"].unitsPerEm
    cap = getattr(f["OS/2"], "sCapHeight", 0) or int(upm * 0.73)
    out.append("    { %d, %d, %d, %s_g, %s_c, %s_p }," % (upm, f["hhea"].ascent, cap, names[fi], names[fi], names[fi]))
out.append("};\n\n#endif")
dst = os.path.join(os.path.dirname(__file__), "..", "..", "engine", "studio", "ui_fonts.h")
open(dst, "w").write("\n".join(out) + "\n")
print("wrote %s: %d points" % (os.path.normpath(dst), total))
