#!/usr/bin/env python3
"""Deadbird hell font: original 5x7 pixel glyphs, fire-gradient fill + dark outline,
written as a 4bpp CLUT TIM (128x32, VRAM (768,0), CLUT (0,482)) and embedded as C.
Cells are 8x10 pixels, 16 per row, in the order of CHARS."""
import os, struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!.:-'/+?<> "

G = {
 'A': ["01110","10001","10001","11111","10001","10001","10001"],
 'B': ["11110","10001","10001","11110","10001","10001","11110"],
 'C': ["01111","10000","10000","10000","10000","10000","01111"],
 'D': ["11110","10001","10001","10001","10001","10001","11110"],
 'E': ["11111","10000","10000","11110","10000","10000","11111"],
 'F': ["11111","10000","10000","11110","10000","10000","10000"],
 'G': ["01111","10000","10000","10011","10001","10001","01111"],
 'H': ["10001","10001","10001","11111","10001","10001","10001"],
 'I': ["11111","00100","00100","00100","00100","00100","11111"],
 'J': ["00111","00010","00010","00010","00010","10010","01100"],
 'K': ["10001","10010","10100","11000","10100","10010","10001"],
 'L': ["10000","10000","10000","10000","10000","10000","11111"],
 'M': ["10001","11011","10101","10101","10001","10001","10001"],
 'N': ["10001","11001","10101","10011","10001","10001","10001"],
 'O': ["01110","10001","10001","10001","10001","10001","01110"],
 'P': ["11110","10001","10001","11110","10000","10000","10000"],
 'Q': ["01110","10001","10001","10001","10101","10010","01101"],
 'R': ["11110","10001","10001","11110","10100","10010","10001"],
 'S': ["01111","10000","10000","01110","00001","00001","11110"],
 'T': ["11111","00100","00100","00100","00100","00100","00100"],
 'U': ["10001","10001","10001","10001","10001","10001","01110"],
 'V': ["10001","10001","10001","10001","10001","01010","00100"],
 'W': ["10001","10001","10001","10101","10101","10101","01010"],
 'X': ["10001","10001","01010","00100","01010","10001","10001"],
 'Y': ["10001","10001","01010","00100","00100","00100","00100"],
 'Z': ["11111","00001","00010","00100","01000","10000","11111"],
 '0': ["01110","10011","10101","10101","10101","11001","01110"],
 '1': ["00100","01100","00100","00100","00100","00100","01110"],
 '2': ["01110","10001","00001","00110","01000","10000","11111"],
 '3': ["11110","00001","00001","01110","00001","00001","11110"],
 '4': ["00010","00110","01010","10010","11111","00010","00010"],
 '5': ["11111","10000","11110","00001","00001","10001","01110"],
 '6': ["00110","01000","10000","11110","10001","10001","01110"],
 '7': ["11111","00001","00010","00100","01000","01000","01000"],
 '8': ["01110","10001","10001","01110","10001","10001","01110"],
 '9': ["01110","10001","10001","01111","00001","00010","01100"],
 '!': ["00100","00100","00100","00100","00100","00000","00100"],
 '.': ["00000","00000","00000","00000","00000","00000","00100"],
 ':': ["00000","00100","00000","00000","00000","00100","00000"],
 '-': ["00000","00000","00000","01110","00000","00000","00000"],
 "'": ["00100","00100","01000","00000","00000","00000","00000"],
 '/': ["00001","00010","00010","00100","01000","01000","10000"],
 '+': ["00000","00100","00100","11111","00100","00100","00000"],
 '?': ["01110","10001","00001","00110","00100","00000","00100"],
 '<': ["00010","00100","01000","10000","01000","00100","00010"],
 '>': ["01000","00100","00010","00001","00010","00100","01000"],
 ' ': ["00000"] * 7,
}

# palette: 0 transparent, 1 outline, 2..8 fire gradient (top -> bottom), 9 hot core highlight
PAL = [(0, 0, 0), (26, 3, 3),
       (255, 248, 200), (255, 226, 120), (255, 188, 60), (250, 140, 34),
       (230, 92, 22), (196, 52, 16), (140, 22, 10), (255, 255, 240)]
PAL += [(0, 0, 0)] * (16 - len(PAL))

W, H, CW, CH = 128, 32, 8, 10
img = [[0] * W for _ in range(H)]
for i, ch in enumerate(CHARS):
    cx, cy = (i % 16) * CW, (i // 16) * CH
    g = G[ch]
    on = lambda x, y: 0 <= x < 5 and 0 <= y < 7 and g[y][x] == '1'
    for y in range(-1, 8):
        for x in range(-1, 6):
            px, py = cx + 1 + x, cy + 1 + y
            if not (0 <= px < W and 0 <= py < H):
                continue
            if on(x, y):
                img[py][px] = 2 + min(6, y)
            elif any(on(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1), (1, 1), (-1, 1))):
                img[py][px] = 1

def c15(r, g, b, i):
    w = (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)
    return w if (w or i == 0) else 0x8000

tim = struct.pack('<II', 0x10, 0x08)                                 # 4bpp + CLUT
tim += struct.pack('<IHHHH', 12 + 32, 0, 482, 16, 1)
tim += struct.pack('<16H', *[c15(*PAL[i], i) for i in range(16)])
tim += struct.pack('<IHHHH', 12 + W // 4 * H * 2, 768, 0, W // 4, H)
for y in range(H):
    for x in range(0, W, 4):
        tim += struct.pack('<H', img[y][x] | (img[y][x + 1] << 4) | (img[y][x + 2] << 8) | (img[y][x + 3] << 12))

open(os.path.join(ROOT, 'assets', 'font.tim'), 'wb').write(tim)
with open(os.path.join(ROOT, 'assets', 'font_tim.h'), 'w') as f:
    f.write(f'/* hell font, 4bpp TIM ({len(tim)} bytes). Generated by tools/make_font.py */\n')
    f.write(f'#define FONT_CHARS "{CHARS}"\n#define FONT_TIM_SIZE {len(tim)}\n')
    f.write(f'static const unsigned char font_tim[{len(tim)}] = {{\n')
    for i in range(0, len(tim), 24):
        f.write('  ' + ','.join(str(b) for b in tim[i:i + 24]) + ',\n')
    f.write('};\n')
print('font.tim', len(tim), 'bytes,', len(CHARS), 'glyphs')
