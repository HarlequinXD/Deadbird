#!/usr/bin/env python3
"""Embed a binary asset (e.g. a .tim) as a C array so it links straight into the
executable -- no file system needed, which is how it will also ship on PS1 (or be
loaded from CD later). Usage: bin2c.py input.tim NAME > output.h"""
import sys

data = open(sys.argv[1], 'rb').read()
name = sys.argv[2]
print(f'/* {sys.argv[1]} embedded ({len(data)} bytes). Generated by tools/bin2c.py */')
print(f'#define {name.upper()}_SIZE {len(data)}')
print(f'static const unsigned char {name}[{len(data)}] = {{')
for i in range(0, len(data), 24):
    print('  ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
print('};')
