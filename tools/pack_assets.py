#!/usr/bin/env python3
"""Packs the authored assets that code can't paint into assets/packed.h, using tools/packer
(gen/pack.c): character / weapon skins, the UI atlas and the title painting as compressed images
(re-quantised to 16-colour CLUTs by the game), the font as 4-bit indices, meshes as coded deltas.

Sources (assets/src/): demon_tex.png soldier_tex.png chainsaw_tex.png pistol_tex.png (RGBA, alpha =
opaque texels), ui_tex.png, font.png (palette image), title_bg.png, *_mesh.json (vertices + prims
with UVs in the 256-texel space of the original sheets; halved here and moved into the VRAM page
given by game/vram.h).
"""
import os, json, subprocess, numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'src')
TMP = os.path.join(ROOT, 'tools', 'out')
os.makedirs(TMP, exist_ok=True)
PACKER = os.path.join(TMP, 'packer')
subprocess.check_call(['cc', '-O2', '-DPACK_ENCODER', '-I', os.path.join(ROOT, 'gen'), '-I', os.path.join(ROOT, 'engine'),
                       '-I', os.path.join(ROOT, 'game'), os.path.join(ROOT, 'tools', 'packer.c'), os.path.join(ROOT, 'gen', 'pack.c'),
                       os.path.join(ROOT, 'gen', 'gmath.c'), '-o', PACKER, '-lm'])

blobs = []


def packer(*args):
    return int(subprocess.check_output([PACKER] + [str(a) for a in args], text=True).strip())


def image(name, rgba, quality):
    h, w = rgba.shape[:2]
    raw, out = os.path.join(TMP, name + '.rgba'), os.path.join(TMP, name + '.pk')
    np.ascontiguousarray(rgba, np.uint8).tofile(raw)
    packer('image', raw, w, h, quality, out, os.path.join(TMP, name + '_decoded.ppm'))
    blobs.append((name, open(out, 'rb').read()))


# UV placement: (u shift, v shift) after halving - see game/vram.h (CHR_* and the pistol's PROPS tile)
SKINS = {'demon': (0, 0, '86f'), 'soldier': (128, 0, '82f'), 'chainsaw': (0, 128, '80f'), 'pistol': (192, 0, '82f')}
for name, (du, dv, q) in SKINS.items():
    image(name + '_tex', np.array(Image.open(os.path.join(SRC, name + '_tex.png')).convert('RGBA')), q)
    m = json.load(open(os.path.join(SRC, name + '_mesh.json')))
    txt = os.path.join(TMP, name + '_mesh.txt')
    with open(txt, 'w') as f:
        f.write(f"{len(m['verts'])} {len(m['prims'])}\n")
        for v in m['verts']:
            f.write(' '.join(map(str, v)) + '\n')
        for p in m['prims']:
            n = p[0]
            u = [(x >> 1) + du if k < n else 0 for k, x in enumerate(p[5:9])]
            t = [(x >> 1) + dv if k < n else 0 for k, x in enumerate(p[9:13])]
            vv = [x if k < n else 0 for k, x in enumerate(p[1:5])]
            f.write(' '.join(map(str, [n] + vv + u + t)) + '\n')
    out = os.path.join(TMP, name + '_mesh.pk')
    packer('mesh', txt, out)
    blobs.append((name + '_mesh', open(out, 'rb').read()))

# UI atlas: cells the game no longer draws (camera turn icons) are left out
ui = np.array(Image.open(os.path.join(SRC, 'ui_tex.png')).convert('RGBA'))
ui[112:144, 64:128, 3] = 0
image('ui_tex', ui, 75)

# title painting (opaque 320x240)
t = np.array(Image.open(os.path.join(SRC, 'title_bg.png')).convert('RGB').resize((320, 240), Image.LANCZOS))
image('title_tex', np.dstack([t, np.full(t.shape[:2], 255, np.uint8)]), 50)

# font: 4-bit indices + its CLUT
f = Image.open(os.path.join(SRC, 'font.png'))
idx = np.array(f, np.uint8)
pal = np.array(f.getpalette()[:48]).reshape(16, 3) // 8
words = [0] + [int(r) | int(g) << 5 | int(b) << 10 | (0x8000 if (r | g | b) == 0 else 0) for r, g, b in pal[1:]]
idx.tofile(os.path.join(TMP, 'font.idx'))
np.array(words, '<u2').tofile(os.path.join(TMP, 'font.clut'))
packer('indexed', os.path.join(TMP, 'font.idx'), idx.shape[1], idx.shape[0], os.path.join(TMP, 'font.clut'), os.path.join(TMP, 'font.pk'))
blobs.append(('font', open(os.path.join(TMP, 'font.pk'), 'rb').read()))

lines = ['/* generated by tools/pack_assets.py from assets/src - see gen/pack.h */', '#ifndef PACKED_H', '#define PACKED_H']
total = 0
for name, b in blobs:
    lines.append(f'static const unsigned char pk_{name}[{len(b)}] = {{')
    for i in range(0, len(b), 40):
        lines.append('  ' + ','.join(str(x) for x in b[i:i + 40]) + ',')
    lines.append('};')
    total += len(b)
    print(f'{name:16s} {len(b):6d} bytes')
lines.append('#endif')
open(os.path.join(ROOT, 'assets', 'packed.h'), 'w').write('\n'.join(lines) + '\n')
print(f'total {total} bytes')
