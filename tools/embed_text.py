#!/usr/bin/env python3
"""Embed a text file as a C string: embed_text.py <in> <out.h> <symbol>"""
import sys
src, out, sym = sys.argv[1:4]
text = open(src).read()
with open(out, 'w') as f:
    f.write('/* generated by tools/embed_text.py from %s - edit that file, then re-run */\n' % src.split('/')[-1])
    f.write('static const char %s[] =\n' % sym)
    for line in text.splitlines():
        f.write('    "%s\\n"\n' % line.replace('\\', '\\\\').replace('"', '\\"'))
    f.write('    ;\n')
