#!/usr/bin/env python3
"""Title backdrop: assets/src/title_bg.png -> 320x240, 256-colour CLUT with PS1 4x4 dither,
as two 8bpp TIMs (columns 0-191 at VRAM (384,0), 192-319 at (512,0); shared CLUT at (0,493)).
The two halves sit in separate texture pages so every quad's U stays inside 0..255.
The backdrop borrows the level's texture-page area while the title is up (the level isn't
drawn there); the level re-uploads its pages when play starts."""
import os, struct
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W, H, SPLIT = 320, 240, 192
img = Image.open(os.path.join(ROOT, 'assets', 'src', 'title_bg.png')).convert('RGB').resize((W, H), Image.LANCZOS)
c8 = np.array(img, float)
pal_img = img.quantize(255, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
pal = np.array(pal_img.getpalette()[:255 * 3], float).reshape(-1, 3)
pal = np.clip(np.round(pal / 8), 0, 31)
pal8 = pal * 8 + pal // 4
DM = np.array([[-4, 0, -3, 1], [2, -2, 3, -1], [-3, 1, -4, 0], [3, -1, 2, -2]], float)
yy, xx = np.mgrid[0:H, 0:W]
tgt = (c8 + (DM[yy % 4, xx % 4] * 2.0)[..., None]).reshape(-1, 3)
idx = np.zeros(W * H, np.uint8)
for s in range(0, len(tgt), 8192):
    idx[s:s + 8192] = ((tgt[s:s + 8192, None, :] - pal8[None]) ** 2).sum(2).argmin(1) + 1
idx = idx.reshape(H, W)
words = [0] + [int(r) | (int(g) << 5) | (int(b) << 10) or 0x8000 for r, g, b in pal]
words = [w | 0x8000 if i and w == 0 else w for i, w in enumerate(words)] + [0] * (256 - len(words))


def tim(part, vx):
    w = part.shape[1]
    return (struct.pack('<II', 0x10, 0x09) + struct.pack('<IHHHH', 12 + 512, 0, 493, 256, 1) + struct.pack('<256H', *words)
            + struct.pack('<IHHHH', 12 + w * H, vx, 0, w // 2, H) + part.tobytes())


out = ['/* generated by tools/make_title_bg.py from assets/src/title_bg.png */']
for name, part, vx in (('titlebg_a', idx[:, :SPLIT], 384), ('titlebg_b', idx[:, SPLIT:], 512)):
    d = tim(np.ascontiguousarray(part), vx)
    out.append(f'#define {name.upper()}_SIZE {len(d)}\nstatic const unsigned char {name}[{len(d)}] = {{')
    out += ['  ' + ','.join(map(str, d[i:i + 32])) + ',' for i in range(0, len(d), 32)]
    out.append('};')
out.append(f'#define TITLEBG_SPLIT {SPLIT}')
open(os.path.join(ROOT, 'assets', 'titlebg_tim.h'), 'w').write('\n'.join(out) + '\n')
rgb = (np.array(words)[:, None] >> np.array([0, 5, 10])) & 31
Image.fromarray((rgb * 8 + rgb // 4).astype(np.uint8)[idx]).resize((640, 480), Image.NEAREST).save('/tmp/titlebg_ps1.png')
print('ok')
